"""
spanish_tools.py - deterministic helpers for Contexto (no AI involved).

Numbers, clock times and clock drawings are RULES, not knowledge, so they are
generated by code and checked by tests (see test_spanish_tools.py).
Usage follows neutral Latin American Spanish (ustedes, no vosotros).
"""
import math

# ---------------------------------------------------------------- numbers
UNITS = [
    "cero", "uno", "dos", "tres", "cuatro", "cinco", "seis", "siete", "ocho",
    "nueve", "diez", "once", "doce", "trece", "catorce", "quince",
    "dieciséis", "diecisiete", "dieciocho", "diecinueve", "veinte",
    "veintiuno", "veintidós", "veintitrés", "veinticuatro", "veinticinco",
    "veintiséis", "veintisiete", "veintiocho", "veintinueve",
]
TENS = {
    30: "treinta", 40: "cuarenta", 50: "cincuenta", 60: "sesenta",
    70: "setenta", 80: "ochenta", 90: "noventa",
}
HUNDREDS = {
    1: "ciento", 2: "doscientos", 3: "trescientos", 4: "cuatrocientos",
    5: "quinientos", 6: "seiscientos", 7: "setecientos", 8: "ochocientos",
    9: "novecientos",
}
MAX_NUMBER = 999_999_999_999  # one step below "un billón" (10**12)


def _below_100(n, last):
    """0-99. `last` is the form used for a final 'one': uno / un / una."""
    if n == 1:
        return last
    if n < 30:
        if n == 21:
            return {"uno": "veintiuno", "un": "veintiún", "una": "veintiuna"}[last]
        return UNITS[n]
    tens, unit = divmod(n, 10)
    word = TENS[tens * 10]
    if unit == 0:
        return word
    return f"{word} y {last if unit == 1 else UNITS[unit]}"


def _below_1000(n, fem, last):
    """1-999. `fem` makes the hundreds feminine (doscientas)."""
    if n == 100:
        return "cien"
    hundreds, rest = divmod(n, 100)
    if hundreds == 0:
        return _below_100(rest, last)
    word = HUNDREDS[hundreds]
    if fem and hundreds >= 2:
        word = word.replace("ientos", "ientas")
    return word if rest == 0 else f"{word} {_below_100(rest, last)}"


def _below_million(n, fem, last):
    """1-999,999."""
    thousands, units = divmod(n, 1000)
    parts = []
    if thousands:
        if thousands == 1:
            parts.append("mil")
        else:
            # the number in front of 'mil' always uses the short form: veintiún mil
            parts.append(_below_1000(thousands, fem, "un") + " mil")
    if units:
        parts.append(_below_1000(units, fem, last))
    return " ".join(parts)


def number_to_spanish(n, gender="m", before_noun=False):
    """
    Spell out an integer in Spanish.

    before_noun=False -> counting / standalone:   21 -> 'veintiuno'
    before_noun=True  -> followed by a noun:      21 -> 'veintiún' (m) / 'veintiuna' (f)
    gender only matters when before_noun=True (201 -> 'doscientas una' + feminine noun).
    """
    if isinstance(n, bool) or not isinstance(n, int):
        raise TypeError("n must be an int")
    if n < 0:
        return "menos " + number_to_spanish(-n, gender, before_noun)
    if n > MAX_NUMBER:
        raise ValueError("Numbers of one billón (10**12) or more are not supported")
    if n == 0:
        return "cero"

    fem = before_noun and gender == "f"
    if before_noun:
        last = "una" if gender == "f" else "un"
    else:
        last = "uno"

    millions, rest = divmod(n, 1_000_000)
    parts = []
    if millions:
        if millions == 1:
            parts.append("un millón")
        else:
            # 'millones' is masculine, so its multiplier is always masculine
            parts.append(_below_million(millions, False, "un") + " millones")
    if rest:
        parts.append(_below_million(rest, fem, last))
    return " ".join(parts)


# ---------------------------------------------------------------- English (for the data builder)
_EN_SMALL = [
    "zero", "one", "two", "three", "four", "five", "six", "seven", "eight",
    "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen",
    "sixteen", "seventeen", "eighteen", "nineteen",
]
_EN_TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy",
            "eighty", "ninety"]


def _en_below_1000(n):
    parts = []
    hundreds, rest = divmod(n, 100)
    if hundreds:
        parts.append(f"{_EN_SMALL[hundreds]} hundred")
    if rest:
        if rest < 20:
            parts.append(_EN_SMALL[rest])
        else:
            tens, unit = divmod(rest, 10)
            parts.append(_EN_TENS[tens] + (f"-{_EN_SMALL[unit]}" if unit else ""))
    return " ".join(parts)


def number_to_english(n):
    """English words for 0 <= n <= MAX_NUMBER (short scale: 10**9 = billion)."""
    if n == 0:
        return "zero"
    parts = []
    for size, name in ((10**9, "billion"), (10**6, "million"), (10**3, "thousand")):
        chunk, n = divmod(n, size)
        if chunk:
            parts.append(f"{_en_below_1000(chunk)} {name}")
    if n:
        parts.append(_en_below_1000(n))
    return " ".join(parts)


# ---------------------------------------------------------------- clock times
def period_of_day(hour24):
    """Part-of-day phrase that follows the time in Latin American Spanish."""
    if hour24 == 0:
        return "de la noche"
    if 1 <= hour24 <= 5:
        return "de la madrugada"
    if 6 <= hour24 <= 11:
        return "de la mañana"
    if hour24 == 12:
        return "del día"
    if 13 <= hour24 <= 19:
        return "de la tarde"
    return "de la noche"


def _hour12(hour24):
    return hour24 % 12 or 12


def _article_and_hour(h12):
    """('Es', 'la una') for 1, ('Son', 'las dos') for the rest."""
    if h12 == 1:
        return "Es", "la una"
    return "Son", f"las {UNITS[h12]}"


def time_to_spanish(hour24, minute, with_period=True):
    """
    The everyday way to say a clock time (12-hour style).
    15:45 -> 'Son las cuatro menos cuarto de la tarde'
    """
    if not (0 <= hour24 <= 23 and 0 <= minute <= 59):
        raise ValueError("hour must be 0-23 and minute 0-59")
    if minute == 0 and hour24 == 12:
        return "Es mediodía"
    if minute == 0 and hour24 == 0:
        return "Es medianoche"

    h12 = _hour12(hour24)
    if minute <= 30:
        verb, hour_text = _article_and_hour(h12)
        if minute == 0:
            phrase = f"{verb} {hour_text}"
        elif minute == 15:
            phrase = f"{verb} {hour_text} y cuarto"
        elif minute == 30:
            phrase = f"{verb} {hour_text} y media"
        else:
            phrase = f"{verb} {hour_text} y {number_to_spanish(minute)}"
    else:
        next_h12 = h12 % 12 + 1
        verb, hour_text = _article_and_hour(next_h12)
        remaining = 60 - minute
        if remaining == 15:
            phrase = f"{verb} {hour_text} menos cuarto"
        else:
            phrase = f"{verb} {hour_text} menos {number_to_spanish(remaining)}"
    return f"{phrase} {period_of_day(hour24)}" if with_period else phrase


def time_variants(hour24, minute):
    """Other common ways to say the same time (needs native-speaker review)."""
    h12 = _hour12(hour24)
    period = period_of_day(hour24)
    variants = []
    if minute == 0 and hour24 not in (0, 12):
        verb, hour_text = _article_and_hour(h12)
        variants.append(f"{verb} {hour_text} en punto {period}")
    if minute == 0 and hour24 == 12:
        variants.append("Son las doce del día")
    if minute == 0 and hour24 == 0:
        variants.append("Son las doce de la noche")
    if minute >= 10:
        verb, hour_text = _article_and_hour(h12)
        variants.append(f"{verb} {hour_text} {number_to_spanish(minute)} {period}")
    if minute > 30:
        next_h12 = h12 % 12 + 1
        _, next_text = _article_and_hour(next_h12)
        remaining = 60 - minute
        word = "para la una" if next_h12 == 1 else f"para las {UNITS[next_h12]}"
        if remaining == 1:
            variants.append(f"Falta un minuto {word} {period}")
        else:
            variants.append(f"Faltan {number_to_spanish(remaining)} {word} {period}")
        if remaining == 15:
            variants.append(f"Un cuarto {word} {period}")
    return variants


# ---------------------------------------------------------------- clock drawing
def clock_svg(hour24, minute, size=160):
    """Return an analog clock as an SVG string (no external images, no licences)."""
    cx = cy = 100
    hour_angle = math.radians(((hour24 % 12) + minute / 60) * 30)
    minute_angle = math.radians(minute * 6)

    def point(angle, length):
        return cx + length * math.sin(angle), cy - length * math.cos(angle)

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" '
        f'width="{size}" height="{size}" role="img" '
        f'aria-label="Clock showing {_hour12(hour24)}:{minute:02d}">',
        '<circle cx="100" cy="100" r="94" fill="#ffffff" stroke="#333333" stroke-width="4"/>',
    ]
    for tick in range(12):
        angle = math.radians(tick * 30)
        x1, y1 = point(angle, 80)
        x2, y2 = point(angle, 90)
        parts.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="#333333" stroke-width="{3 if tick % 3 == 0 else 1.5}"/>'
        )
    for number in (12, 3, 6, 9):
        x, y = point(math.radians(number * 30), 66)
        parts.append(
            f'<text x="{x:.1f}" y="{y + 6:.1f}" text-anchor="middle" '
            f'font-family="sans-serif" font-size="18" font-weight="bold" fill="#333333">{number}</text>'
        )
    hx, hy = point(hour_angle, 48)
    mx, my = point(minute_angle, 72)
    parts.append(
        f'<line x1="100" y1="100" x2="{hx:.1f}" y2="{hy:.1f}" stroke="#111111" '
        f'stroke-width="7" stroke-linecap="round"/>'
    )
    parts.append(
        f'<line x1="100" y1="100" x2="{mx:.1f}" y2="{my:.1f}" stroke="#c0392b" '
        f'stroke-width="4" stroke-linecap="round"/>'
    )
    parts.append('<circle cx="100" cy="100" r="5" fill="#111111"/>')
    label = "a. m." if hour24 < 12 else "p. m."
    parts.append(
        f'<text x="100" y="150" text-anchor="middle" font-family="sans-serif" '
        f'font-size="14" fill="#555555">{label}</text>'
    )
    parts.append("</svg>")
    return "".join(parts)
