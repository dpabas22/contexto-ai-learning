# ------------------------------------------------------------- math
OPS = {"+": ("más", lambda a, b: a + b),
       "-": ("menos", lambda a, b: a - b),
       "*": ("por", lambda a, b: a * b),
       "/": ("entre", lambda a, b: Fraction(a, b))}


def evaluate(tokens):
    """Evaluate [num, op, num, ...] with normal precedence (× and ÷ first)."""
    values, ops = [tokens[0]], []
    for op, num in zip(tokens[1::2], tokens[2::2]):
        if op in "*/":
            values[-1] = OPS[op][1](values[-1], num)
        else:
            values.append(num)
            ops.append(op)
    result = values[0]
    for op, num in zip(ops, values[1:]):
        result = OPS[op][1](result, num)
    return result


SYMBOL = {"+": "+", "-": "−", "*": "×", "/": "÷"}


def math_example(tokens, note=None):
    result = evaluate(tokens)
    assert result.denominator == 1 if isinstance(result, Fraction) else True
    result = int(result)
    parts = []
    for token in tokens:
        parts.append(es(token) if isinstance(token, int) else OPS[token][0])
    verb = "es" if result == 1 else "son"
    spanish = f"{' '.join(parts)} {verb} {es(result)}".capitalize()
    shown = " ".join(f"{t:,}" if isinstance(t, int) else SYMBOL[t] for t in tokens)
    item = {"expression": f"{shown} = {result:,}", "spanish": spanish}
    if note:
        item["note"] = note
    return item


